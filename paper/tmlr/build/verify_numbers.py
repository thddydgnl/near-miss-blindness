# Normalize LaTeX so that "$-0.031$ [$-0.039$, $-0.025$]" and "$-$0.01" read as "-0.031 [-0.039, -0.025]", "-0.01".
TEX = RAW.replace("$", "").replace("\\%", "%").replace("{,}", ",")

FAILS, N = [], 0


def load(rel):
    with open(os.path.join(RES, rel)) as fh:
        return json.load(fh)


def fmt(x, nd=3, sign=False):
    q = 10 ** nd
    v = math.copysign(math.floor(abs(x) * q + 0.5) / q, x)
    s = f"{abs(v):.{nd}f}"
    if float(s) == 0:
        return s
    return ("-" if v < 0 else ("+" if sign else "")) + s


def _check(label, got, want):
    global N
    N += 1
    if got != want:
        FAILS.append(f"{label}: JSON gives '{got}', paper uses '{want}'")
    elif want not in TEX:
        FAILS.append(f"{label}: '{want}' not found in main.tex")


def eq(label, got, want):
    """Equality only, for values that are not quoted verbatim in the text."""
    global N
    N += 1
    if got != want:
        FAILS.append(f"{label}: got '{got}', expected '{want}'")


def chk(label, x, want, nd=None, sign=False):
    nd = nd if nd is not None else len(want.lstrip("+-").split(".")[1]) if "." in want else 0
    _check(label, fmt(x, nd, sign), want)


def ci(label, x, lo, hi, want, nd=None, sign=False):
    """Point estimate with its interval, e.g. '0.100 [0.075, 0.125]'."""
    nd = nd if nd is not None else len(want.split(" [")[0].lstrip("+-").split(".")[1])
    _check(label, f"{fmt(x, nd, sign)} [{fmt(lo, nd)}, {fmt(hi, nd)}]", want)


def rng(label, lo, hi, want, sep="--", nd=None):
    a = want.split(sep)[0]
    nd = nd if nd is not None else len(a.split(".")[1])
    _check(label, f"{fmt(lo, nd)}{sep}{fmt(hi, nd)}", want)


def doc(label, want, report):
    global N
    N += 1
    text = open(os.path.join(B_ROOT, "main", report)).read()
    if want not in TEX:
        FAILS.append(f"{label}: '{want}' not found in main.tex")
    elif want.replace(",", "") not in text.replace(",", "") and want not in text:
        FAILS.append(f"{label}: '{want}' not found in {report}")



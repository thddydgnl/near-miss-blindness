"""Check every number quoted in the TMLR manuscript against the frozen results.

Two kinds of checks:
  * chk / ci / rng  -- the value is recomputed from main/results/*.json, rounded the way the paper prints it
    (half away from zero), and must (1) equal the string the paper uses and (2) appear in main.tex.
  * doc             -- values that exist only in the stage reports (costs, a few judge statistics): the string
    must appear both in main.tex and in the named report under main/reports or main/LOG.md.
Tables generated by make_tables.py are correct by construction and are not re-checked here.
Run from anywhere:  python3 paper/tmlr/build/verify_numbers.py
"""

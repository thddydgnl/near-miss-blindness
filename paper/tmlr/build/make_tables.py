"""LaTeX table bodies for the TMLR manuscript, written straight from the frozen analysis JSON in main/results.

Tables with many numbers are generated here so that no value is typed by hand; main.tex \\input's the files.
Run from anywhere:  python3 paper/tmlr/build/make_tables.py
Outputs: paper/tmlr/tables/*.tex
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TMLR = os.path.normpath(os.path.join(HERE, ".."))
RES = os.path.normpath(os.path.join(TMLR, "..", "..", "main", "results"))
OUT = os.path.join(TMLR, "tables")


def load(rel):
    with open(os.path.join(RES, rel)) as f:
        return json.load(f)


def f(v, nd=3, sign=False):
    """Fixed-point number with a typographic minus sign; '+' only when asked and the value is nonzero."""
    s = f"{abs(v):.{nd}f}"
    if float(s) == 0:
        return s
    return ("$-$" if v < 0 else ("$+$" if sign else "")) + s


def ci(lo, hi, nd=3):
    return f"[{f(lo, nd)}, {f(hi, nd)}]"


def write(name, lines):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    with open(path, "w") as fh:
        fh.write("% generated by paper/tmlr/build/make_tables.py from main/results -- do not edit by hand\n")
        fh.write("\n".join(lines) + "\n")
    return path


# ---------------------------------------------------------------- Table 3: M3 predictor capacity / representation sweep
def tab_capacity():
    sw = load("E4_server/e4_analysis.json")["4b_sweep"]
    rows = [("base", "Default: 64 tokens, PCA 64, predictor width 128, 4 layers"),
            ("R3", "Smaller predictor: width 64, 2 layers"),
            ("R4", "Larger predictor: width 256, 8 layers"),
            ("R1", "More tokens: 256 tokens, PCA 64"),
            ("R2", "Wider tokens: 64 tokens, PCA 384")]
    out = []
    for k, lab in rows:
        c = sw[k]
        out.append(f"{lab} & {f(c['auc_sn_real'])} & {f(c['auc_sn_imag'])} & {f(c['auc_sn_ceiling'])} & "
                   f"{f(c['NM'])} & {f(c['SM'])} \\\\")
    return write("tab_capacity.tex", out)


# ---------------------------------------------------------------- Table 4: data-side remedies at matched exposure
def tab_remedies():
    h = load("E5_server/e5_analysis.json")["H5a"]
    sets = [("M1", "M1, $r$, $H=5$"), ("M3_p0.03", "M3, $p=0.03$"), ("M3_p0.1", "M3, $p=0.1$")]
    keys = ["ref", "rw", "near", "cp", "full", "bw"]
    out = []
    for k, lab in sets:
        c = h[k]
        cells = " & ".join(f"{f(c[p]['NM'])} / {f(c[p]['SM'])}" for p in keys)
        d = c["near_minus_rw"]["NM"]
        out.append(f"{lab} & {cells} & {f(d['diff'], sign=True)} {ci(*d['ci'])} \\\\")
    return write("tab_remedies.tex", out)


# ---------------------------------------------------------------- Appendix: all M1 counterfactual cells, judge (a)
def tab_m1_cells():
    cells = load("E1_server/m1/e1_m1_analysis.json")["cells"]
    out = []
    for split, split_lab in (("val", "val"), ("trainsplit", "train")):
        for d, dlab in (("r", "$r$"), ("r_obj", "$r_{\\rm obj}$")):
            for h in (3, 5, 7, 10):
                c = cells[f"{split}/H{h}/{d}"]["a"]
                out.append(f"{split_lab} & {dlab} & {h} & {c['n']['near']:,} & {f(c['p_near_real'])} & "
                           f"{f(c['p_success_imag'])} & {f(c['p_near_imag'])} & {f(c['p_far_imag'])} & "
                           f"{f(c['auc_sn_real'])} & {f(c['auc_sn_imag'])} & {f(c['auc_sn_ceiling'])} & "
                           f"{f(c['delta_auc_sn'])} & {f(c['delta_auc_sf'])} \\\\")
            out.append("\\addlinespace")
    return write("tabF_m1_cells.tex", out[:-1])



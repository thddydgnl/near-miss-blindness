# ---------------------------------------------------------------- Appendix: M2 by number of chained chunks, and probe
def tab_m2_k():
    m2 = load("E1_m2/analysis/e1_analysis.json")
    out = []
    for judge, jlab in (("a", "(a) reference"), ("c", "(c) value head"), ("d", "(d) VLM")):
        pt = m2["cells"][f"{judge}|pooled6"]["point"]
        for k, klab in (("real", "real"), ("k1", "1 chunk"), ("k2", "2 chunks"), ("k3", "3 chunks"),
                        ("k4", "4 chunks")):
            c = pt[k]
            out.append(f"{jlab if k == 'real' else ''} & {klab} & {f(c['success'])} & {f(c['near'])} & "
                       f"{f(c['mid'])} & {f(c['far'])} & {f(c['auroc_near'])} & {f(c['auroc_far'])} \\\\")
        out.append("\\addlinespace")
    d3 = m2["D3"]
    for k, klab in (("feat_real", "real"), ("feat_imag_k1", "1 chunk"), ("feat_imag_k2", "2 chunks"),
                    ("feat_imag_k3", "3 chunks"), ("feat_imag_k4", "4 chunks")):
        c = d3[k]["pooled6"]
        out.append(f"{'feature probe' if k == 'feat_real' else ''} & {klab} & & & & & {f(c['auroc_near'])} & "
                   f"{f(c['auroc_far'])} \\\\")
    return write("tabF_m2_k.tex", out)


def tab_m2_tasks():
    m2 = load("E1_m2/analysis/e1_analysis.json")
    names = {"t1": "t1 bowl on stove", "t2": "t2 bottle on cabinet", "t4": "t4 bowl on cabinet",
             "t5": "t5 plate to stove front", "t6": "t6 cheese in bowl", "t8": "t8 bowl on plate"}
    out = []
    for t in ("t1", "t2", "t4", "t5", "t6", "t8"):
        pt = m2["cells"][f"a|{t}"]["point"]
        c, r = pt["k1"], pt["real"]
        out.append(f"{names[t]} & {f(r['near'])} & {f(c['success'])} & {f(c['near'])} & {f(c['far'])} & "
                   f"{f(c['d_auroc_near'])} & {f(c['d_auroc_far'])} & {f(pt['horizon_slope_near'])} \\\\")
    pt = m2["cells"]["a|pooled6"]["point"]
    c, r = pt["k1"], pt["real"]
    out.append("\\midrule")
    out.append(f"six tasks pooled & {f(r['near'])} & {f(c['success'])} & {f(c['near'])} & {f(c['far'])} & "
               f"{f(c['d_auroc_near'])} & {f(c['d_auroc_far'])} & {f(pt['horizon_slope_near'])} \\\\")
    return write("tabF_m2_tasks.tex", out)


